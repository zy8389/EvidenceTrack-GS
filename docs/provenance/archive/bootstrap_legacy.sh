#!/usr/bin/env bash
# LEGACY REPRODUCIBLE PACKAGE ASSEMBLER.
# This script is not used by the materialized main repository and retains the
# old package-relative paths only as provenance. For an executable copy, check
# out the `reproducible-package-2026-09-17` tag and follow its README.
# Reconstruct the project from immutable upstream + one cumulative patch + overlay.
# This assembler intentionally performs no compile, test, CUDA, or training work.
set -euo pipefail
HERE=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
if [[ ! -d "$HERE/patches" || ! -d "$HERE/scripts" ]]; then
  echo 'Legacy assembler: not executable from the materialized main repository.' >&2
  echo 'Check out tag reproducible-package-2026-09-17 to reproduce the package assembly.' >&2
  exit 2
fi
DEST=${1:?Usage: bash scripts/bootstrap.sh /absolute/new/GeoTrack-GS}
REF=81ada6a32c918591ae7c7a0279dc6ca7a8018e2f
[[ ! -e "$DEST" ]] || { echo 'Destination must not exist. Your existing work is never overwritten.' >&2; exit 2; }
git clone --no-checkout https://github.com/CPy255/GeoTrack-GS.git "$DEST"
git -C "$DEST" config core.autocrlf false
git -C "$DEST" checkout --detach "$REF"
[[ "$(git -C "$DEST" rev-parse HEAD)" == "$REF" ]] || {
  echo 'Pinned upstream checkout did not resolve to the required commit.' >&2
  exit 2
}
git -C "$DEST" submodule update --init --recursive
# The patch is generated from this exact pre-AST base.  Keep `git apply --check`
# immediately before application: the AST integration below must never be used to
# hide a drifting patch or a post-integration patch generated by mistake.
git -C "$DEST" apply --check "$HERE/patches/phase2_1_integrity.patch"
git -C "$DEST" apply "$HERE/patches/phase2_1_integrity.patch"
# Overlay the current research modules before applying the guarded integration
# transformations.  The copied integration script is invoked from DEST so it
# sees exactly the files that will be used by the assembled checkout.
for dir in diffusion_guidance geometric_constraints tools tests configs; do
  [[ -d "$HERE/$dir" ]] || { echo "Missing package overlay directory: $HERE/$dir" >&2; exit 2; }
  mkdir -p "$DEST/$dir"; cp -a "$HERE/$dir/." "$DEST/$dir/"
done
mkdir -p "$DEST/research_scripts"
cp -a "$HERE/scripts/." "$DEST/scripts/"
[[ -f "$DEST/scripts/apply_integration_fixes.py" ]] || {
  echo 'Missing guarded integration script after overlay copy.' >&2
  exit 2
}
python "$DEST/scripts/apply_integration_fixes.py" "$DEST"
cp "$HERE/requirements-"*.txt "$DEST/"
if [[ -d "$HERE/../docs" ]]; then
  mkdir -p "$DEST/research_docs"
  cp -a "$HERE/../docs/." "$DEST/docs/"
fi
printf '\nAssembled source only: %s\nNo compile, CPU, CUDA, or training checks were run. Follow docs/FERN_PRECHECK_AND_RUN.md, beginning with the explicit environment gate.\n' "$DEST"
